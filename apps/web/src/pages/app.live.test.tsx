/**
 * Live application sweep: every route, against a REAL FastAPI backend.
 *
 *   cd services/api && python -m uvicorn app.main:app --port 8000
 *   cd apps/web && VITE_API_BASE=http://127.0.0.1:8000/api/v1 npm test
 *
 * Skipped unless the suite is started with that base URL, so a plain `npm test` stays green.
 *
 * For every page it asserts that
 *   1. the synthetic-data banner is present,
 *   2. real engine content arrives (each page has a content hint taken from the seed dataset),
 *   3. none of the failure markers appear: no "load failed" panel, no network error, no NaN.
 *
 * With `RCA_WRITE_SNAPSHOT=1` it also writes `docs/samples/ui-render-snapshot.md` — the text that
 * each page actually rendered. That is deliberately *evidence instead of a screenshot*: no browser
 * is available in the build environment, so the artefact records what jsdom really rendered from the
 * live API rather than a hand-drawn mock.
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

import { cleanup, render, screen, waitFor } from "@testing-library/react";
import { MemoryRouter } from "react-router-dom";
import { describe, expect, it } from "vitest";

import App from "@/App";

const LIVE_BASE = "http://127.0.0.1:8000/api/v1";
const configuredBase = ((import.meta.env.VITE_API_BASE as string | undefined) ?? "").replace(/\/+$/, "");
const liveEnabled = configuredBase === LIVE_BASE;
const writeSnapshot = process.env.RCA_WRITE_SNAPSHOT === "1";
/** `npm test` runs with cwd = apps/web, so the repository root is two levels up. */
const SNAPSHOT_PATH = resolve(process.cwd(), "../../docs/samples/ui-render-snapshot.md");

type PageSpec = {
  path: string;
  name: string;
  /** Content that only the live API can produce. */
  hint: RegExp;
};

const PAGES: PageSpec[] = [
  { path: "/", name: "Overview (总览)", hint: /\$322,305/ },
  // −3.96% is the FY2024 revenue variance; seeing it proves the plan table is scoped to the
  // fiscal year rather than to the whole dataset.
  { path: "/pnl", name: "P&L analysis (损益分析)", hint: /3\.96%/ },
  { path: "/risk", name: "Risk control (风险控制)", hint: /RC-01/ },
  { path: "/market", name: "Market intelligence (市场情报)", hint: /4\.83/ },
  { path: "/scenarios", name: "Scenario simulator (情景模拟)", hint: /Upside/ },
  // The analyst page resolves its month range from `/health`; while loading it reads
  // "当前月份范围 不可用", so a leading non-"不" character proves the dataset arrived.
  { path: "/analyst", name: "AI analyst (AI 分析师)", hint: /当前月份范围 [^不]/ },
  { path: "/reports", name: "Report centre (报告中心)", hint: /数据截止 2024年12月/ },
];

const FAILURE_MARKERS: Array<[string, RegExp]> = [
  ["load-failure panel", /加载失败/],
  ["connection error", /无法连接后端/],
  ["client network error", /NetworkError/],
  ["NaN leak", /\bNaN\b/],
  ["undefined leak", /undefined USD/],
];

/** The shell is still fetching `/health` while these strings are on screen. */
const SHELL_LOADING = /正在读取 \/health/;

function bodyText(): string {
  return (document.body.textContent ?? "").replace(/\s+/g, " ").trim();
}

function renderRoute(path: string) {
  return render(
    <MemoryRouter initialEntries={[path]}>
      <App />
    </MemoryRouter>,
  );
}

describe.skipIf(!liveEnabled)(`live application sweep (${LIVE_BASE})`, () => {
  it(
    "renders every page from the live API without a failure state",
    async () => {
      const collected: Array<{ page: PageSpec; text: string }> = [];

      for (const page of PAGES) {
        renderRoute(page.path);
        try {
          // 1. The shell must finish /health before the page content is judged, otherwise a
          //    skeleton satisfies any loose assertion.
          await waitFor(() => expect(bodyText()).not.toMatch(SHELL_LOADING), { timeout: 25000 });
          // 2. Then the page must show content that only the live API can produce.
          await waitFor(() => expect(bodyText()).toMatch(page.hint), { timeout: 25000 });
          expect(screen.getByTestId("synthetic-banner")).toBeInTheDocument();
          const text = bodyText();
          for (const [label, pattern] of FAILURE_MARKERS) {
            expect(text, `${page.name}: ${label}`).not.toMatch(pattern);
          }
          expect(text, `${page.name}: the as-of date must come from the API`).toMatch(/数据截止 2024年12月/);
          expect(text.length, `${page.name}: rendered text is suspiciously short`).toBeGreaterThan(400);
          collected.push({ page, text });
        } finally {
          cleanup();
        }
      }

      expect(collected).toHaveLength(PAGES.length);

      if (writeSnapshot) {
        mkdirSync(dirname(SNAPSHOT_PATH), { recursive: true });
        const rendered = [
          "# UI render snapshot (from the live API)",
          "",
          "Generated by `apps/web/src/pages/app.live.test.tsx` with `RCA_WRITE_SNAPSHOT=1` against a",
          "running FastAPI service on `http://127.0.0.1:8000`. This is the **text that jsdom actually",
          "rendered** from real API responses — evidence in place of a browser screenshot, which the build",
          "environment could not capture. Regenerate:",
          "",
          "```bash",
          "cd services/api && python -m uvicorn app.main:app --port 8000 &",
          "cd apps/web && VITE_API_BASE=http://127.0.0.1:8000/api/v1 RCA_WRITE_SNAPSHOT=1 npm test",
          "```",
          "",
          `All figures come from the shipped synthetic dataset (seed 20260101). ${PAGES.length} routes,`,
          "each captured after the live data finished loading.",
          "",
        ].join("\n");

        const sections = collected.map(({ page, text }) =>
          [
            `## ${page.name} — \`${page.path}\``,
            "",
            "```text",
            text.length > 2600 ? `${text.slice(0, 2600)} … [truncated]` : text,
            "```",
            "",
          ].join("\n"),
        );

        writeFileSync(SNAPSHOT_PATH, `${rendered}${sections.join("\n")}`, "utf8");
      }
    },
    180000,
  );

  it("keeps the synthetic banner on every route", async () => {
    for (const page of PAGES) {
      renderRoute(page.path);
      try {
        expect(screen.getByTestId("synthetic-banner").textContent).toContain("SYNTHETIC DEMO");
        await waitFor(() => expect(bodyText()).not.toMatch(SHELL_LOADING), { timeout: 25000 });
        expect(bodyText().length).toBeGreaterThan(400);
      } finally {
        cleanup();
      }
    }
  }, 180000);

  it("answers from a shareable /analyst?q= deep link", async () => {
    renderRoute(`/analyst?q=${encodeURIComponent("我们的风险和现金状况如何？")}`);
    try {
      await waitFor(() => expect(bodyText()).toMatch(/RC-01/), { timeout: 30000 });
      // A real answer: cited findings come from the deterministic engine's tool results.
      expect(bodyText()).toMatch(/risk:register\.score/);
      expect(bodyText()).toMatch(/deterministic-planner/);
      for (const [label, pattern] of FAILURE_MARKERS) {
        expect(bodyText(), `analyst deep link: ${label}`).not.toMatch(pattern);
      }
    } finally {
      cleanup();
    }
  }, 120000);

  it("generates and verifies a report from a shareable /reports?auto=1 deep link", async () => {
    renderRoute("/reports?auto=1&months=12");
    try {
      await waitFor(() => expect(bodyText()).toMatch(/RCA-\d{6}-[0-9a-f]{6}/), { timeout: 40000 });
      expect(bodyText()).toMatch(/V-01/);
      expect(bodyText()).toMatch(/V-02/);
      for (const [label, pattern] of FAILURE_MARKERS) {
        expect(bodyText(), `report deep link: ${label}`).not.toMatch(pattern);
      }
    } finally {
      cleanup();
    }
  }, 120000);
});

if (!liveEnabled) {
  describe("live application sweep", () => {
    it.skip("set VITE_API_BASE=http://127.0.0.1:8000/api/v1 and start the API to enable this", () => undefined);
  });
}
